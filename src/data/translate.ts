  s = s.replace(/ＨＩＴ/g, "HIT");
  s = s.replace(/（/g, "(").replace(/）/g, ")");
  s = applyPairs(s, [...GRAMMAR, ...PHRASES, ...INFLECT]);
  const held = protectProper(s);
  s = toTraditional(held.text);
  s = applyPairs(s, YUE_AFTER);
  s = s.replace(/の/g, "的");
  s = s.replace(/[がをはもへ]/g, "");
