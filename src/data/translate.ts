  s = s.replace(/約(\d+(?:\.\d+)?)秒ごと/g, "每約$1秒");
  s = s.replace(/通常の射撃(\d+)ＨＩＴにかかる時間と[、,]ほぼ同時間で(\d+)ＨＩＴする/g, "在通常射擊打出 $1 HIT 所需的時間內，打出 $2 HIT");
