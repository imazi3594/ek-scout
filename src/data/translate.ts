  s = s.replace(/ＨＩＴ/g, "HIT");
  s = s.replace(/（/g, "(").replace(/）/g, ")");
  s = applyPairs(s, [...GRAMMAR, ...PHRASES, ...INFLECT]);
  const held = protectProper(s);
  s = toTraditional(held.text);
  s = applyPairs(s, YUE_AFTER);
  const keptQuotes: string[] = [];
  s = s.replace(/「[^」]*」/g, (m) => {
    if (!/[\u3040-\u30FF]/.test(m)) return m;
    const token = `§Q${keptQuotes.length}§`;
    keptQuotes.push(m);
    return token;
  });
  s = s.replace(/の/g, "的");
  s = s.replace(/[がをはもへ]/g, "");
  s = s.replace(/に/g, "");
  s = s.replace(/と/g, "與");
  s = s.replace(/で/g, "以");
  s = s.replace(/[\u3040-\u309F\u30A0-\u30FA\u30FC-\u30FF]+/g, "");
  s = s.replace(/(\d+)[体體]/g, "$1隊");
