export function ryuhaTheme(title: string) {
  const ura = title.includes("裏");
  const kind = title.split("・")[0] ?? "";
  const pal = RYUHA_INK[kind];
  if (!pal) return null;
  if (!ura) {
    return {
      ura,
      head: pal.accent,
      cardBg: pal.accent,
      cardFg: pal.onAccent,
      factBg: PAPER,
      factFg: INK,
      muted: pal.onAccent,
      factMuted: "rgb(26 22 18 / 0.58)",
    };
  }
  return {
    ura,
    head: pal.accent,
    cardBg: PAPER,
    cardFg: INK,
    factBg: pal.accent,
    factFg: pal.onAccent,
    muted: "rgb(26 22 18 / 0.62)",
    factMuted: pal.onAccent,
  };
}

